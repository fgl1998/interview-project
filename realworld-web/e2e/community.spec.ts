import { test, expect } from '@playwright/test'
import { mockJavaApi, login } from './java-api'

test('desktop community: browse, comment, favorite, authors, follow and publish', async ({
  page,
}) => {
  const backend = await mockJavaApi(page)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await login(page)
  await expect(page.getByRole('heading', { name: '让想法在这里发生。' })).toBeVisible()
  await expect(page.locator('.article-card')).toHaveCount(10)
  await page.getByLabel('第 2 页', { exact: true }).click()
  await expect(page.locator('.article-card')).toHaveCount(1)
  await page.getByLabel('搜索文章').fill('Vue')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page).toHaveURL(/q=Vue/)
  await page.locator('.article-main-link').first().click()
  await expect(page.getByRole('heading', { name: '从 Vue 3 开始，构建更清晰的前端' })).toBeVisible()
  await page.getByTestId('favorite').click()
  await expect(page.getByTestId('favorite')).toContainText('已收藏')
  await page.getByLabel('评论内容').fill('清晰的实践，感谢分享。')
  await page.getByRole('button', { name: '发表评论' }).click()
  await expect(page.locator('.comment-body')).toContainText('清晰的实践，感谢分享。')
  await page.getByRole('button', { name: '删除评论' }).click()
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.comment-item')).toHaveCount(0)
  expect(await page.evaluate(() => 'injected' in window)).toBe(false)
  await page.getByRole('link', { name: '查看作者主页 →' }).click()
  await expect(page.getByRole('heading', { name: 'writer', exact: true })).toBeVisible()
  await expect(page.getByTestId('tab-favorites')).toHaveCount(0)
  await page.getByTestId('follow').click()
  await expect(page.getByTestId('follow')).toContainText('已关注')
  await page.getByTestId('tab-followers').click()
  await expect(page.locator('.relation-card')).toContainText('fang')
  await page.getByTestId('follow').click()
  await expect(page.getByTestId('follow')).toContainText('关注作者')
  await page.getByRole('link', { name: '写文章', exact: true }).click()
  await page.getByLabel('文章标题').fill('我的第一篇 Web 文章')
  await page.getByLabel('文章摘要').fill('用 Vue 3 和 Element Plus 记录实践。')
  await page.getByRole('group', { name: '话题标签' }).getByText('Vue', { exact: true }).click()
  await expect(page.getByLabel('Vue', { exact: true })).toBeChecked()
  await page.getByLabel('文章正文').fill('## 开始\n一步一步，把想法变成现实。')
  await page.getByText('预览', { exact: true }).click()
  await expect(page.getByRole('radio', { name: '预览', exact: true })).toBeChecked()
  await expect(page.locator('.editor-preview')).toContainText('开始')
  await page.getByRole('button', { name: '发布文章', exact: true }).click()
  await expect(page).toHaveURL(/profiles\/fang$/)
  await expect(page.locator('.article-card').first()).toContainText('我的第一篇 Web 文章')
  await page.getByTestId('tab-favorites').click()
  await expect(page.locator('.article-card')).toHaveCount(1)
  await page.getByTestId('tab-following').click()
  await expect(page.getByRole('heading', { name: '还没有关注其他作者' })).toBeVisible()
  expect(
    backend.requests.find((r) => r.path.endsWith('/queryArticlesByAuthorId'))?.body.authorId,
  ).toBe(12)
  expect(
    backend.requests
      .filter((r) => r.path.endsWith('/queryArticlesByAuthorId'))
      .some((r) => r.body.authorId === 7),
  ).toBe(true)
  expect(
    backend.requests.find((r) => r.path.endsWith('/create') && r.body.title)?.body.tagsId,
  ).toEqual([1])
  expect(errors).toEqual([])
  await page.goto('/')
  await expect(page.locator('.article-card')).toHaveCount(10)
  await page.screenshot({ path: 'test-results/desktop-home.png', fullPage: true })
})

test('profile updates retain username, omit empty password and persist after refresh', async ({
  page,
}) => {
  const backend = await mockJavaApi(page)
  await login(page, '/settings')
  await expect(page.getByLabel('用户名', { exact: true })).toBeDisabled()
  await page.getByLabel('邮箱', { exact: true }).fill('new@example.org')
  await page.getByLabel('个人简介').fill('新的个人简介')
  await page.getByRole('button', { name: '保存修改' }).click()
  await expect(page.getByText('个人信息已保存', { exact: true })).toBeVisible()
  const update = backend.requests.find((r) => r.path === '/api/users/update')
  expect(update?.body).toEqual({ id: 7, email: 'new@example.org', bio: '新的个人简介', image: '' })
  await page.reload()
  await expect(page.getByLabel('邮箱', { exact: true })).toHaveValue('new@example.org')
  await page.getByRole('link', { name: '← 返回我的主页' }).click()
  await expect(page.locator('.profile-heading')).toContainText('新的个人简介')
  expect(backend.user.username).toBe('fang')
})

test('failed saves, feed retries and business 401 remain usable', async ({ page }) => {
  const backend = await mockJavaApi(page)
  await login(page, '/settings')
  backend.failUpdate()
  await page.getByLabel('邮箱', { exact: true }).fill('duplicate@example.org')
  await page.getByRole('button', { name: '保存修改' }).click()
  await expect(page.getByRole('alert')).toContainText('邮箱已被使用')
  await expect(page.getByLabel('邮箱', { exact: true })).toHaveValue('duplicate@example.org')
  expect(backend.user.email).toBe('fang@example.org')
  backend.failFeed(true)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '暂时无法加载' })).toBeVisible()
  backend.failFeed(false)
  await page.getByRole('button', { name: '重新加载' }).click()
  await expect(page.locator('.article-card')).toHaveCount(10)
  backend.expire()
  await page.locator('.article-main-link').first().click()
  await expect(page).toHaveURL(/login\?redirect=/)
  expect(await page.evaluate(() => localStorage.getItem('realworld.web.session'))).toBeNull()
})

test('registration and deep link guards work on a mobile viewport', async ({ page }) => {
  await mockJavaApi(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/articles/article-1')
  await expect(page).toHaveURL(/login\?redirect=/)
  await page.getByRole('link', { name: '立即注册' }).click()
  await page.getByLabel('用户名', { exact: true }).fill('newuser')
  await page.getByLabel('邮箱', { exact: true }).fill('newuser@example.org')
  await page.getByLabel('密码', { exact: true }).fill('123456')
  await page.getByLabel('确认密码', { exact: true }).fill('123456')
  await page.getByRole('button', { name: '创建账户' }).click()
  await expect(page).toHaveURL(/login\?/)
  await expect(page.getByLabel('用户名', { exact: true })).toHaveValue('newuser')
  await page.getByLabel('用户名', { exact: true }).fill('fang')
  await page.getByLabel('密码', { exact: true }).fill('123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/articles\/article-1$/)
  await expect(page.getByRole('heading', { name: '从 Vue 3 开始，构建更清晰的前端' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true,
  )
  await page.screenshot({ path: 'test-results/mobile-article.png', fullPage: true })
  await page.reload()
  await expect(page.locator('.article-author-panel')).toBeVisible()
  await page.goto('/a-page-that-does-not-exist')
  await expect(page.getByRole('heading', { name: '这页故事还不存在' })).toBeVisible()
})

test('deleting my own article requires confirmation and returns to the feed', async ({ page }) => {
  const backend = await mockJavaApi(page)
  await login(page, '/articles/article-2')
  await page.getByRole('button', { name: '删除我的文章' }).click()
  expect(backend.articles.some((a) => a.id === 11)).toBe(true)
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page).toHaveURL('http://127.0.0.1:5174/')
  expect(backend.articles.some((a) => a.id === 11)).toBe(false)
})
